"""Validation harness — Argus Enterprise Unbound Gateway Phase I cashflow.

Source: ``validation/fixtures/argus_cashflow/Unbound Gateway - Phase I_Cash Flow_*.xls``
(generated by Argus Enterprise 2026.06.01).

Unbound is the cleanest of the 5 Argus exports — zero general vacancy /
credit loss across all 11 years and no rollover until Y11 — which makes it
the deal we pin OpenVal's top-line parity against. The ``ARGUS_PINNED``
golden dict below is the published truth.

Pinning rule (Y1–Y10): every numeric row of the Argus top-line block (PBR,
A&T Vacancy, Free Rent, SBR, TRR, Recoveries, Vacancy + Credit Loss, EGR)
must match the golden number within ``$25`` per cell — enough headroom for
Argus's whole-dollar monthly rounding to compose with float arithmetic on
OpenVal's side, tight enough to catch any real engine drift. Y11 is
excluded — the original lease rolls over there and Argus runs the rollover
with explicit downtime + free rent, while the stub uses
``renewal_probability=1.0`` (instant renewal) to keep the rest of the
horizon stable. Tunable, not a bug.

Run as a script for the human-readable side-by-side:

    .venv/bin/python validation/argus_unbound.py

The pytest test in ``tests/test_argus_unbound.py`` calls
``assert_matches_argus()`` so any engine change that drifts a stabilized
year breaks CI.
"""

