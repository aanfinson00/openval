# Window where we expect $-for-$ engine parity. Y1..Y10 inclusive — Y1
# matches once we feed Argus's actual opex (which has a partial-year
# Property Management Fee component during lease-up; OpenVal's recovery
# engine already prorates by occupied months, so the schedule reproduces
# Y1 recoveries exactly). Y11 is excluded — it's partial because of the
# original lease rolling over, which the stub models as instant renewal
# (renewal_probability=1.0) rather than the explicit downtime + free rent
# Argus runs at lease end.
